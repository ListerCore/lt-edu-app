import 'server-only';
import type { CallOptions, ClientUnaryCall, Metadata, ServiceError } from '@grpc/grpc-js';
import { grpcCall, type GrpcCallOptions, type GrpcResult } from './client';
import { DocumentsServiceClient } from './gen/joseph/documents/v1/documents';

type Unary<Req, Res> = (request: Req, metadata: Metadata, options: Partial<CallOptions>, callback: (error: ServiceError | null, response: Res) => void) => ClientUnaryCall;
type Call<Req, Res> = (request: Req, options: GrpcCallOptions & { token: string }) => Promise<GrpcResult<Res>>;
type PublicCall<Req, Res> = (request: Req, options?: GrpcCallOptions) => Promise<GrpcResult<Res>>;

// Binds one DocumentsService method to the shared call helper (auth metadata, deadline, error mapping)
const documents =
  <Req, Res>(pick: (client: DocumentsServiceClient) => Unary<Req, Res>): Call<Req, Res> =>
  (request, options) =>
    grpcCall(DocumentsServiceClient, (client, md, opts, cb) => pick(client).call(client, request, md, opts, cb), options);

// Binds a public method (no session: the QR tracking page); the visitor's IP still travels for the rate limit
const publicDocuments =
  <Req, Res>(pick: (client: DocumentsServiceClient) => Unary<Req, Res>): PublicCall<Req, Res> =>
  (request, options = {}) =>
    grpcCall(DocumentsServiceClient, (client, md, opts, cb) => pick(client).call(client, request, md, opts, cb), options);

